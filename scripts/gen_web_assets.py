# Generates src/web_assets.h: the web UI (src/web_ui.h) and the manual (src/help_ui.h)
# gzip-compressed, plus an ETag per page. The web server sends the compressed bytes with
# "Content-Encoding: gzip" and answers repeat visits with 304 Not Modified.
# Runs automatically before every PlatformIO build (extra_scripts = pre:...);
# can also be run by hand: python3 scripts/gen_web_assets.py
import gzip, hashlib, os, re

def generate(project_dir):
    pages = [("INDEX_HTML", "src/web_ui.h"), ("HELP_HTML", "src/help_ui.h")]
    out = ["// Generated by scripts/gen_web_assets.py – do not edit", "#pragma once", "#include <Arduino.h>", ""]
    for name, src in pages:
        text = open(os.path.join(project_dir, src), encoding="utf-8").read()
        m = re.search(r'%s\[\] PROGMEM = R"HTML\((.*?)\)HTML";' % name, text, re.S)
        if not m:
            raise SystemExit("gen_web_assets: %s not found in %s" % (name, src))
        raw = m.group(1).encode("utf-8")
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        etag = hashlib.sha1(raw).hexdigest()[:16]
        body = ",".join(str(b) for b in gz)
        out.append("// %s: %d bytes → %d bytes gzip" % (src, len(raw), len(gz)))
        out.append("static const uint8_t %s_GZ[] PROGMEM = {%s};" % (name, body))
        out.append('static const char %s_ETAG[] = "\\"%s\\"";' % (name, etag))
        out.append("")
        print("gen_web_assets: %s %d → %d bytes (gzip)" % (src, len(raw), len(gz)))
    dst = os.path.join(project_dir, "src/web_assets.h")
    content = "\n".join(out)
    if not os.path.exists(dst) or open(dst, encoding="utf-8").read() != content:
        open(dst, "w", encoding="utf-8").write(content)

try:
    Import("env")  # noqa: F821 – defined when run by PlatformIO
    generate(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    generate(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
